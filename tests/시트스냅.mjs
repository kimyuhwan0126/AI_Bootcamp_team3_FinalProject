/* `lib/시트스냅.ts` 회귀 시험 — 화면도 DB도 dev 서버도 필요 없다(`tests/지도셈.mjs` 머리말 참고).

   돌리는 법:  npm test */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { 가장가까운, 홈스냅 } from '../lib/시트스냅.ts';

/* 모임 화면(`app/m/[code]/ui.tsx`)이 실제로 쓰는 자리들. vh=800 기준. */
const 모임자리 = ['mini', 'default', 'big'];
const 모임픽셀 = (s) => (s === 'mini' ? 76 : s === 'big' ? 800 * 0.82 : 800 * 0.56);

/* 홈 시트가 쓸 자리들(목업 core.js 1678–1684). 시트높이 752 · 남는높이 816 기준.
   목업의 '살짝'(30%)은 2026-08-19 에 사람이 정해 뺐다 — app/홈/시트끌기.ts 머리말. */
const 홈자리 = ['미니', '반', '가득'];
const 홈픽셀 = (s) => ({ 미니: 752 - 106, 반: 752 - 449, 가득: 752 - 734 })[s];

test('딱 그 자리에 있으면 그 자리를 고른다', () => {
  for (const s of 모임자리) assert.equal(가장가까운(모임픽셀(s), 모임자리, 모임픽셀), s);
  for (const s of 홈자리) assert.equal(가장가까운(홈픽셀(s), 홈자리, 홈픽셀), s);
});

test('가까운 쪽으로 붙는다', () => {
  /* mini 76 · default 448 · big 656 */
  assert.equal(가장가까운(90, 모임자리, 모임픽셀), 'mini');
  assert.equal(가장가까운(400, 모임자리, 모임픽셀), 'default');
  assert.equal(가장가까운(700, 모임자리, 모임픽셀), 'big');
});

test('한가운데를 살짝 넘으면 넘어간다', () => {
  const 중간 = (76 + 448) / 2;              /* 262 */
  assert.equal(가장가까운(중간 - 1, 모임자리, 모임픽셀), 'mini');
  assert.equal(가장가까운(중간 + 1, 모임자리, 모임픽셀), 'default');
});

test('동점이면 배열에서 앞엣것이 이긴다', () => {
  /* 예전 `ui.tsx` 의 반복문도 mini 를 먼저 훑어 같은 거리면 mini 가 남았다.
     그 성질을 고쳐 놓으면 손을 정확히 중간에서 뗐을 때 시트가 반대로 튄다.

     ⚠ 진짜 동점은 정수로만 만들 수 있다 — 실제 자리 값은 `800 * 0.56 = 448.00000000000006`
     이라 한가운데조차 6자리 뒤에서 갈린다(이 시험을 처음 쓸 때 여기 걸렸다).
     그러니 이 성질은 정수 자리로 못 박는다. */
  const 값 = (s) => ({ 위: 0, 아래: 100 })[s];
  assert.equal(가장가까운(50, ['위', '아래'], 값), '위');
  assert.equal(가장가까운(50, ['아래', '위'], 값), '아래');
});

test('범위 밖으로 끌어도 끝 자리로 붙는다', () => {
  assert.equal(가장가까운(-500, 모임자리, 모임픽셀), 'mini');
  assert.equal(가장가까운(99999, 모임자리, 모임픽셀), 'big');
});

test('자리가 하나뿐이면 늘 그것', () => {
  assert.equal(가장가까운(12345, ['숨김'], () => 0), '숨김');
});

/* ── 홈 시트의 정착 자리 ────────────────────────────────── */

/* 402×874 폰에 전역 탭바(58px). 시트는 CSS 로 셸의 86% = 752px. */
const 잰것 = { 시트높이: 752, 셸높이: 874, 탭바높이: 58, 손잡이높이: 32, 요약높이: 62 };

test('홈스냅 — 숨김은 시트를 화면 밖으로 완전히 민다', () => {
  const s = 홈스냅(잰것);
  /* 시트 높이보다 더 밀어야 그림자까지 안 보인다 */
  assert.ok(s.숨김 > 잰것.시트높이, `${s.숨김} 은 ${잰것.시트높이} 보다 커야 한다`);
});

test('홈스냅 — 미니는 손잡이와 요약 줄만 남긴다', () => {
  const s = 홈스냅(잰것);
  const 보이는높이 = 잰것.시트높이 - s.미니;
  assert.equal(보이는높이, 잰것.손잡이높이 + 잰것.요약높이);
});

test('홈스냅 — 자리 차례대로 시트가 점점 많이 보인다', () => {
  const s = 홈스냅(잰것);
  const 차례 = ['숨김', '미니', '반', '가득'];
  const 보이는 = 차례.map((k) => 잰것.시트높이 - s[k]);
  for (let i = 1; i < 보이는.length; i++) {
    assert.ok(보이는[i] > 보이는[i - 1],
      `${차례[i]}(${보이는[i]}) 가 ${차례[i - 1]}(${보이는[i - 1]}) 보다 많이 보여야 한다`);
  }
});

test('홈스냅 — 반·가득은 남는 높이의 55·90%', () => {
  const s = 홈스냅(잰것);
  const 남는높이 = 잰것.셸높이 - 잰것.탭바높이;      /* 816 */
  assert.equal(잰것.시트높이 - s.반, Math.round(남는높이 * 0.55));
  assert.equal(잰것.시트높이 - s.가득, Math.round(남는높이 * 0.90));
});

test('홈스냅 — 뺀 자리(살짝)는 다시 안 생긴다', () => {
  /* 2026-08-19 에 사람이 정해 뺀 확장 2단계다. 셈만 되살아나 자리가 넷으로
     돌아가는 일을 막는다 — 되살릴 일이 생기면 사람에게 먼저 묻는다. */
  assert.deepEqual(Object.keys(홈스냅(잰것)), ['숨김', '미니', '반', '가득']);
});

test('홈스냅 — 탭바가 내려가 있으면 남는 높이가 늘어난다', () => {
  /* browse 모드에서 지도를 탭하면 탭바가 미끄러져 내려간다 — 그때는 그 자리도 시트 몫이다 */
  const 탭바있음 = 홈스냅(잰것);
  const 탭바없음 = 홈스냅({ ...잰것, 탭바높이: 0 });
  assert.ok(잰것.시트높이 - 탭바없음.가득 > 잰것.시트높이 - 탭바있음.가득);
});

test('홈스냅 — 아직 안 붙어 크기가 0 이어도 안 터진다', () => {
  const s = 홈스냅({ 시트높이: 0, 셸높이: 0, 탭바높이: 58, 손잡이높이: 0, 요약높이: 0 });
  for (const [이름, 값] of Object.entries(s)) {
    assert.ok(Number.isFinite(값), `${이름} 이 ${값}`);
  }
});

test('홈스냅 + 가장가까운 — 반쯤 끌다 놓으면 가까운 자리로 붙는다', () => {
  const s = 홈스냅(잰것);
  const 차례 = ['미니', '반', '가득'];
  const 값 = (k) => s[k];
  /* 딱 그 자리에서 놓으면 그 자리 */
  for (const k of 차례) assert.equal(가장가까운(s[k], 차례, 값), k);
  /* 미니와 반 사이 — 미니 쪽에서 놓으면 미니, 반 쪽에서 놓으면 반.
     '살짝'을 뺀 뒤로 이 사이가 가장 넓은 구간이라 여기서 잰다. */
  const 중간 = (s.미니 + s.반) / 2;
  assert.equal(가장가까운(중간 + 5, 차례, 값), '미니');
  assert.equal(가장가까운(중간 - 5, 차례, 값), '반');
});
