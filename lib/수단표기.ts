import type { Transport } from './types';

/** 고르는 자리(세그 단추)에 쓰는 이름 — 만들기 폼과 같은 말이다(app/originfield.tsx:209) */
export const 수단이름: Record<Transport, string> = { transit: '대중교통', car: '자동차' };

/**
 * 칩에 붙는 한 마디 — 고른 카테고리 그대로다.
 *
 * @param 수단  이 출발지에 사람이 고른 값
 */
export function 수단표기(수단: Transport): string {
  return 수단이름[수단];
}
