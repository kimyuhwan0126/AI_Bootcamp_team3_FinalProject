//    빌드 시점에 문자열로 치환된다. 그래서 `process.env[key]` 처럼 동적으로 읽으면
//    안 되고 반드시 아래처럼 통째로 써야 한다.
//
// ⚠️ 꺼진 기능은 썩는다. 플래그를 켠 상태의 스모크 테스트를 CI에 함께 돌린다
//    (.github/workflows/ci.yml). 안 돌려보는 플래그는 "언제든 켤 수 있는 코드"가
//    아니라 "켤 수 있어 보이는 죽은 코드"다.
