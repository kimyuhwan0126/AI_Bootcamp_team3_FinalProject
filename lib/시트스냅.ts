/* 바텀시트가 '손 뗀 자리에서 가장 가까운 정착 자리'를 고르는 셈.

   ⚠ **두 시트가 나눠 쓰는 것은 이 셈 하나뿐이다.** 나머지는 합치지 마라 —
     · `app/m/[code]/ui.tsx` 의 시트는 `max-height` 를 몰아 **위에 있는 `.map`(flex:1)을 줄인다.**
       `globals.css:22–26` 의 `min-height:0` 이 없으면 데스크톱 크롬에 가로 스크롤바가 났다.
     · 홈의 시트는 `inset:0` 으로 깔린 지도 **위를** `transform` 으로 덮는다. 지도는 안 줄어든다.
   둘을 한 물건으로 만들려면 모임 화면의 배치 모형을 통째로 바꿔야 하는데, 그 화면은
   `tests/css.mjs`·`screen.mjs`·`map.mjs` 셋이 겨누는 이 저장소에서 가장 시험이 두꺼운 자리다.
   홈 이식과 그 회귀를 한 덩어리로 묶으면 되돌릴 수가 없다.

   합칠 값이 있는 것은 '가장 가까운 자리 고르기' 뿐이라 그것만 여기 둔다. */

/**
 * 지금 값에서 가장 가까운 정착 자리를 고른다.
 *
 * @param 지금   손을 뗀 순간의 값 (모임 화면은 시트 높이 px, 홈은 translateY 오프셋 px)
 * @param 자리들 정착 자리 이름들. 같은 거리면 **앞엣것**이 이긴다 —
 *               부르는 쪽이 배열 차례로 우선순위를 정할 수 있게(홈은 `미니` 를 앞에 둔다).
 * @param 값     자리 이름 → 그 자리의 값
 */
export function 가장가까운<T extends string>(
  지금: number,
  자리들: readonly T[],
  값: (자리: T) => number,
): T {
  let 고른것 = 자리들[0], 최소거리 = Infinity;
  for (const 자리 of 자리들) {
    const 거리 = Math.abs(지금 - 값(자리));
    /* `<` 이지 `<=` 가 아니다 — 같은 거리면 앞엣것이 남는다(위 주석) */
    if (거리 < 최소거리) { 최소거리 = 거리; 고른것 = 자리; }
  }
  return 고른것;
}
