/* 바텀시트가 '손 뗀 자리에서 가장 가까운 정착 자리'를 고르는 셈.

   ⚠ **두 시트가 나눠 쓰는 것은 이 셈 하나뿐이다.** 나머지는 합치지 마라 —
     · `app/m/[code]/ui.tsx` 의 시트는 `max-height` 를 몰아 **위에 있는 `.map`(flex:1)을 줄인다.**
       `globals.css:22–26` 의 `min-height:0` 이 없으면 데스크톱 크롬에 가로 스크롤바가 났다.
     · 홈의 시트는 `inset:0` 으로 깔린 지도 **위를** `transform` 으로 덮는다. 지도는 안 줄어든다.
   둘을 한 물건으로 만들려면 모임 화면의 배치 모형을 통째로 바꿔야 하는데, 그 화면은
   `tests/css.mjs`·`screen.mjs`·`map.mjs` 셋이 겨누는 이 저장소에서 가장 시험이 두꺼운 자리다.
   홈 이식과 그 회귀를 한 덩어리로 묶으면 되돌릴 수가 없다.

   합칠 값이 있는 것은 '가장 가까운 자리 고르기' 뿐이라 그것만 여기 둔다. */

/**
 * 지금 값에서 가장 가까운 정착 자리를 고른다.
 *
 * @param 지금   손을 뗀 순간의 값 (모임 화면은 시트 높이 px, 홈은 translateY 오프셋 px)
 * @param 자리들 정착 자리 이름들. 같은 거리면 **앞엣것**이 이긴다 —
 *               부르는 쪽이 배열 차례로 우선순위를 정할 수 있게(홈은 `미니` 를 앞에 둔다).
 * @param 값     자리 이름 → 그 자리의 값
 */
export function 가장가까운<T extends string>(
  지금: number,
  자리들: readonly T[],
  값: (자리: T) => number,
): T {
  let 고른것 = 자리들[0], 최소거리 = Infinity;
  for (const 자리 of 자리들) {
    const 거리 = Math.abs(지금 - 값(자리));
    /* `<` 이지 `<=` 가 아니다 — 같은 거리면 앞엣것이 남는다(위 주석) */
    if (거리 < 최소거리) { 최소거리 = 거리; 고른것 = 자리; }
  }
  return 고른것;
}

/* ── 홈 시트의 정착 자리 셈 ────────────────────────────────
   목업 `moimer-core.js` 의 layout()(1671–1690)에서 옮겼다. 화면을 안 읽는 순수 셈이라
   여기 둔다 — 여백 셈과 마찬가지로 **눈으로는 틀린 걸 못 알아챈다**(시트 밑단이 탭바에
   몇 px 깔리는지는 글자가 잘려야 비로소 보인다). CI 가 대신 잰다.

   모임 화면은 이 함수를 안 쓴다 — 저기는 자리가 셋이고 뜻도 다르다(위 머리말). */

export type 홈자리 = '숨김' | '미니' | '반' | '가득';

/* 남는 높이(셸 − 탭바)의 몇 %를 시트가 덮는가. 목업 값 그대로.
   ⚠ 목업에는 `살짝: 0.30` 이 하나 더 있었다 — 확장 2단계다. 2026-08-19 에 사람이
   정해 뺐다(app/홈/시트끌기.ts 머리말). 되살릴 일이 생기면 사람에게 먼저 묻는다. */
const 비율 = { 반: 0.55, 가득: 0.90 } as const;

/**
 * 자리마다 시트를 얼마나 **아래로 밀지**(translateY, px)를 셈한다.
 * 값이 클수록 시트가 아래에 있다 — 0 이면 시트 위끝이 제자리다.
 *
 * @param 잰것.시트높이   시트 상자의 실제 높이(CSS 로 셸의 86%)
 * @param 잰것.셸높이     셸 상자의 실제 높이
 * @param 잰것.탭바높이   전역 탭바가 먹는 높이. 미끄러져 내려가 있으면 0
 * @param 잰것.손잡이높이 손잡이 줄 높이
 * @param 잰것.요약높이   시트요약 줄 높이 — '미니'에서 이 줄까지는 보여야 한다
 */
export function 홈스냅(잰것: {
  시트높이: number; 셸높이: number; 탭바높이: number;
  손잡이높이: number; 요약높이: number;
}): Record<홈자리, number> {
  const { 시트높이, 셸높이, 탭바높이, 손잡이높이, 요약높이 } = 잰것;
  const 남는높이 = Math.max(0, 셸높이 - 탭바높이);
  return {
    /* 화면 밖으로 완전히. +10 은 그림자까지 안 보이게 하는 여유(목업 값). */
    숨김: 시트높이 + 10,
    /* 손잡이 + 요약 줄만 남기고 나머지는 내린다 */
    미니: 시트높이 - (손잡이높이 + 요약높이),
    반: 시트높이 - Math.round(남는높이 * 비율.반),
    가득: 시트높이 - Math.round(남는높이 * 비율.가득),
  };
}
