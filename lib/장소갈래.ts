/**
 * 이 장소가 어느 갈래인가. 모르면 null.
 *
 * @param 갈래말 `/api/places` 가 준 `category` — 카카오 갈래 이름이거나 OSM 태그다.
 * @param 상세   카카오가 준 `categoryDetail`("음식점 > 술집 > 호프,요리주점"). 술집을
 *               음식점에서 갈라내는 것은 이것뿐이다(위 머리말).
 */
export function 갈래고르기(갈래말?: string | null, 상세?: string | null): 갈래 | null {
  if ((상세 ?? '').includes('술집')) return '술집';
  const 말 = (갈래말 ?? '').trim();
  if (!말) return null;
  return 한글표[말] ?? 영어표[말.toLowerCase()] ?? null;
}

/** 그 갈래의 아이콘 — 모르는 갈래는 `모름아이콘` 이다.
    갈래 이름을 이미 아는 자리(칩 줄)는 이걸 안 거치고 `갈래들` 의 것을 그대로 쓴다. */
export function 아이콘고르기(갈래: 갈래 | null | undefined): 아이콘 {
  return (갈래 && 갈래들.find((x) => x.이름 === 갈래)?.아이콘) || 모름아이콘;
}

/** 그 갈래의 색 — 모르는 갈래는 `모름색` 이다(위 `갈래색` 머리말) */
export function 색고르기(갈래: 갈래 | null | undefined): string {
  return (갈래 && 갈래색[갈래]) || 모름색;
}
