'use client';
/* 바텀시트의 **둘레 장소** 갈래 — 탐색 모드에서 지도 표식을 눌러 들어온 자리
   (2026-08-20 사용자 요청, 참고 그림 ③).

   무엇을 적는가 — 참고 그림에서 **덜어 낸 것부터** 적는다. 사람이 못 박았다:
     ⚠ 별점 · 후기 수 · 후기 목록을 **안 적는다.**
     ⚠ '62m' 같은 **거리도 안 적는다.**
   덜어 낸 까닭은 우리가 그 값을 가지고 있지 않아서만은 아니다 — 홈의 거리는 늘
   '중간지점에서'인데, 참고 그림의 거리는 '내 위치에서'다. 같은 숫자처럼 보이면서
   다른 것을 세는 값을 나란히 두면 읽는 사람이 틀리게 읽는다.
   사진도 없다: 카카오 로컬이 사진을 안 준다(그리로 가는 길만 아래 링크로 둔다).

   남는 것 셋 — 전화 · 카카오 장소 페이지 · 주소. 셋 다 **있을 때만** 선다:
   빈 줄을 '—' 로 채워 두면 아직 못 받은 것인지 원래 없는 것인지 알 수 없다.

   ⚠ **이름을 여기 안 적는다**(2026-08-20 사람이 정했다). 잠깐 맨 위에 큰 글씨로
   한 번 더 적었다가 같은 날 뺐다 — 시트 요약 줄(홈.tsx 의 `.시트요약`)이 이름과 갈래를
   이미 쥐고 있고, 그 줄은 시트를 끝까지 내려도 남는 자리다. 요약 줄 바로 밑에 같은
   이름이 또 서면 한 화면에 같은 말이 두 번 있게 된다.
   ⚠ 중간지점 시트(시트내용_가운데.tsx)는 아직 `.큰글` 로 이름을 겹쳐 적는다 — 거기까지
   같이 고치는 것은 시킨 일이 아니라 그대로 뒀다. */

import s from './홈.module.css';

/* 줄머리 그림. 무엇을 가리키는 값인지 글자 없이 말한다 — 값 자체(전화번호·주소)가
   이미 무엇인지 말하고 있어 '전화' 같은 이름표를 또 세우면 한 줄이 두 번 말한다. */
const 그림 = {
  전화: <path d="M6.5 3h3l1.5 4-2 1.5a12 12 0 0 0 5.5 5.5L16 12l4 1.5v3a2 2 0 0 1-2.2 2A16 16 0 0 1 4.5 5.2 2 2 0 0 1 6.5 3Z" />,
  누리집: <>
    <path d="M12 3a9 9 0 1 0 0 18 9 9 0 0 0 0-18Z" />
    <path d="M3 12h18" />
    <path d="M12 3c2.5 2.6 3.8 5.6 3.8 9s-1.3 6.4-3.8 9c-2.5-2.6-3.8-5.6-3.8-9S9.5 5.6 12 3Z" />
  </>,
  주소: <>
    <path d="M12 21s7-7.4 7-12a7 7 0 1 0-14 0c0 4.6 7 12 7 12Z" />
    <path d="M12 6.5a2.5 2.5 0 1 0 0 5 2.5 2.5 0 0 0 0-5Z" />
  </>,
};

function 줄머리({ 갈래 }: { 갈래: keyof typeof 그림 }) {
  return (
    <svg className={s.정보그림} width="18" height="18" viewBox="0 0 24 24" fill="none"
      stroke="currentColor" strokeWidth="1.9" strokeLinecap="round" strokeLinejoin="round"
      aria-hidden="true">{그림[갈래]}</svg>
  );
}

export default function 시트내용장소({ 장소 }: {
  /* 이름은 안 그리지만 그대로 받는다 — 전화 단추의 `aria-label` 이 "어디에 거는
     전화인가" 를 말해야 한다. 요약 줄과 이 칸은 서로 다른 자리라 눈으로 잇지 못하는
     사람도 있다(시트내용_출발지.tsx 가 `출발지` 를 받는 것과 같은 까닭). */
  장소: { name: string; address: string; phone?: string; url?: string };
}) {
  return (
    <div data-slot="시트-장소">
      <div className={s.정보들}>
        {/* 전화는 **누를 수 있어야 한다** — 폰에서 보는 화면이고, 번호를 손으로 옮겨
            적는 것이 이 줄의 유일한 쓸모라면 링크가 아닐 까닭이 없다. */}
        {!!장소.phone && (
          <a className={s.정보줄} href={`tel:${장소.phone.replace(/[^0-9+]/g, '')}`}
            data-slot="장소전화" aria-label={`${장소.name} 에 전화 걸기 ${장소.phone}`}>
            <줄머리 갈래="전화" />
            <span className={s.정보값}>{장소.phone}</span>
          </a>
        )}

        {/* 사진·메뉴·영업시간은 우리가 안 받아 온다 — 그것들이 있는 곳으로 가는 길만 둔다.
            새 탭으로 연다: 여기서 나가면 넣어 둔 출발지가 있는 화면을 잃는다. */}
        {!!장소.url && (
          <a className={s.정보줄} href={장소.url} target="_blank" rel="noreferrer"
            data-slot="장소바깥link">
            <줄머리 갈래="누리집" />
            <span className={s.정보값}>카카오맵에서 보기</span>
          </a>
        )}

        {!!장소.address && (
          <p className={s.정보줄} data-slot="장소주소">
            <줄머리 갈래="주소" />
            <span className={s.정보값}>{장소.address}</span>
          </p>
        )}
      </div>
    </div>
  );
}
