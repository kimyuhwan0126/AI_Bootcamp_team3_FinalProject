/* 출발지 핀 그림 — 번호가 박힌 물방울.

   ⚠ **디자인과 움직임은 나중에 바뀐다**(2026-08-19 사람이 그렇게 말했다).
   그래서 고칠 값은 전부 아래 `핀` 하나에 이름을 달아 모아 뒀다 —
   목업(core.js 1440–1462)처럼 `(7 - 2.4 * t)` 같은 숫자를 식 안에 흩어 두지 않았다.
   **모양을 바꾸려면 이 파일 맨 위 `핀` 만 고치면 된다.** 부르는 쪽(지도.tsx)은 안 건드려도 된다.

   색은 정하지 않는다 — 부르는 쪽이 준다. 위 출발지 칩과 **같은 색표**를 써야
   '이 칩이 저 핀'이 한눈에 읽힌다(`출발지색`, app/홈/윗칸.tsx).

   ⚠ 핀을 **끄는 기능은 없다**(사람이 정했다). 그래서 `뜬정도` 를 움직이는 것은
   지금은 '고른 핀' 하나뿐이다. 나중에 다른 손짓(hover 든 무엇이든)에 걸고 싶어져도
   이 파일은 안 고쳐도 된다 — 0~1 을 받는 것이 전부이기 때문이다. */

