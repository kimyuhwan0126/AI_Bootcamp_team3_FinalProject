/** [처음, 끝] 사이를 `t`(0~1)로 섞는다 */
const 섞기 = ([a, b]: readonly [number, number], t: number) => a + (b - a) * t;
/** SVG 속성에 넣을 만큼만 자른다 — 소수점이 길어지면 data URI 만 길어진다 */
const 자릿수 = (n: number) => Number(n.toFixed(2));

export type 핀모양 = {
  /** 핀에 적을 번호. 1부터. */
  번호: number;
  /** 물방울 색. 출발지 칩과 같은 색을 준다. */
  색: string;
  /** 얼마나 떠 있나. 0 = 바닥에 붙음 · 1 = 다 뜸. 기본 0. */
  뜬정도?: number;
};

/** 핀 하나를 SVG 문자열로 그린다. */
export function 핀그림({ 번호, 색, 뜬정도 = 0 }: 핀모양): string {
  const t = Math.max(0, Math.min(1, 뜬정도));
  const 뜸 = 자릿수(핀.뜨는높이 * t);
  const ㄱ = 핀.바닥그림자, ㄴ = 핀.드롭섀도;

  /* 필터 id 가 한 문서 안에서 겹치면 나중 것이 앞 것을 덮는다 — 핀마다 다르게 짓는다 */
  const 필터id = `핀그늘${번호}`;

  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${핀.폭}" height="${핀.높이}" ` +
      `viewBox="0 0 ${핀.폭} ${핀.높이}">` +
      `<defs><filter id="${필터id}" x="-60%" y="-30%" width="220%" height="180%">` +
        `<feDropShadow dx="0" dy="${자릿수(섞기(ㄴ.dy, t))}" ` +
          `stdDeviation="${자릿수(섞기(ㄴ.번짐, t))}" ` +
          `flood-color="${ㄴ.색}" flood-opacity="${자릿수(섞기(ㄴ.투명도, t))}"/>` +
      `</filter></defs>` +
      `<ellipse cx="${ㄱ.cx}" cy="${ㄱ.cy}" rx="${자릿수(섞기(ㄱ.rx, t))}" ` +
        `ry="${자릿수(섞기(ㄱ.ry, t))}" fill="${ㄱ.색}" ` +
        `fill-opacity="${자릿수(섞기(ㄱ.투명도, t))}"/>` +
      `<g filter="url(#${필터id})" transform="translate(0,-${뜸})">` +
        `<path d="${핀.몸통}" fill="${색}" stroke="${핀.테두리색}" ` +
          `stroke-width="${핀.테두리두께}"/>` +
        `<circle cx="${핀.글자원.cx}" cy="${핀.글자원.cy}" r="${핀.글자원.r}" fill="#fff"/>` +
        `<text x="${핀.글자.x}" y="${핀.글자.y}" text-anchor="middle" ` +
          `font-size="${핀.글자.크기}" font-weight="${핀.글자.굵기}" ` +
          `font-family="system-ui,sans-serif" fill="${색}">${번호}</text>` +
      `</g>` +
    `</svg>`
  );
}

/** 브라우저에 바로 넣을 수 있는 data URI. `<img src>` 와 카카오 MarkerImage 가 함께 쓴다. */
export const 핀주소 = (모양: 핀모양) =>
  'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(핀그림(모양));

/** 핀 그림을 좌표에 맞추는 밀기 — 물방울 **끝**이 좌표에 닿게 한다.
    카카오도 OSM 도 이 값을 그대로 쓴다(두 지도가 같은 자리에 찍혀야 한다). */
export const 핀밀기 = { x: -핀.폭 / 2, y: -핀.끝점y } as const;
